#pragma once

#include "..\\..\\System\\GameBase.h"

#include <GameLoop.h>

class SceneBase : public KaguyaEngine::GameLoop
{
public:

	//=============================================================================
	// コンストラクタ
	// 引　数：Engine* エンジンクラスのアドレス
	//=============================================================================
	SceneBase();

	//=============================================================================
	// 仮想デストラクタ
	//=============================================================================
	virtual ~SceneBase();

	//=============================================================================
	// Run関数の実行時に１度だけ呼び出される開始処理関数（純粋仮想関数）
	//=============================================================================
	virtual void Start() = 0;

	//=============================================================================
	// Run関数内で実行される更新処理用関数（純粋仮想関数）
	//=============================================================================
	virtual void Update() = 0;

	//=============================================================================
	// Run関数内で実行される描画処理用関数（純粋仮想関数）
	//=============================================================================
	virtual void Draw2D() = 0;

protected:

	//複数のシーンで共用するデータ構造体
	static Common::CommonData m_gameData;
};